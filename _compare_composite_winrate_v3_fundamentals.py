def md_table(records):
    if not records:
        return "_(no records)_"
    cols = ["strategy", "trades", "win%", "avg%", "med%", "expectancy%", "PF",
            "avg_hold", "stop%", "tp%", "time%"]
    head = ["策略", "笔数", "胜率%", "均收益%", "中位%", "期望%", "PF", "持有天", "止损%", "止盈%", "时间%"]
    lines = ["| " + " | ".join(head) + " |",
             "|" + "|".join(["---"] * len(head)) + "|"]
    for r in records:
        cells = [f"{r.get(c, '—')}" for c in cols]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


