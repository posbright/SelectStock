# ---------------- universe loading --------------------------------------------
def load_universe(force: bool = False) -> dict[str, pd.DataFrame]:
    if not force and os.path.isfile(KCACHE):
        with open(KCACHE, "rb") as fh:
            return pickle.load(fh)
    top = pd.read_pickle(UNIV_FILE)
    out: dict[str, pd.DataFrame] = {}
    codes = top["code"].astype(str).str.zfill(6).tolist()
    for i, code in enumerate(codes, 1):
        try:
            df = load_stock_data(code, START, END)
        except Exception as e:
            print(f"  [{i:>3}/{len(codes)}] {code} ERROR {e}"); continue
        if df is None or len(df) < 250:
            print(f"  [{i:>3}/{len(codes)}] {code} skip n={0 if df is None else len(df)}"); continue
        out[code] = df.reset_index(drop=True)
        print(f"  [{i:>3}/{len(codes)}] {code} ok {len(df):>4} rows")
    with open(KCACHE, "wb") as fh:
        pickle.dump(out, fh)
    return out


# ---------------- trade simulator ---------------------------------------------
@dataclass
class Trade:
    code: str
    entry_bar: int
    entry_date: pd.Timestamp
    entry_price: float
    exit_bar: int
    exit_date: pd.Timestamp
    exit_price: float
    reason: str               # "stop-loss" | "win-target" | "time-exit"
    gross_ret: float
    net_ret: float            # net of round-trip cost
    hold_days: int


def simulate(code: str, df_enriched: pd.DataFrame, sig: pd.Series,
             stop_loss: float = 0.05, take_profit: float = 0.10,
             max_hold: int = 20) -> list[Trade]:
    """
    Walk forward; whenever signal fires AND no open position, enter at next-bar
    open; exit on first of stop/take/time.
    """
    n = len(df_enriched)
    if n == 0:
        return []
    opn = df_enriched["open"].values
    hi  = df_enriched["high"].values
    lo  = df_enriched["low"].values
    cls = df_enriched["close"].values
    dts = df_enriched["date"].values
    sig_arr = sig.values

    trades: list[Trade] = []
    i = 0
    while i < n - 2:
        if not sig_arr[i]:
            i += 1
            continue
        # entry = next bar's open
        eb = i + 1
        if eb >= n:
            break
        entry = opn[eb]
        if not np.isfinite(entry) or entry <= 0:
            i = eb + 1
            continue
        target = entry * (1 + take_profit)
        stop   = entry * (1 - stop_loss)
        out_bar, out_price, reason = None, None, None
        for j in range(eb, min(eb + max_hold + 1, n)):
            # check stop FIRST (conservative — if both touched same day, assume stop)
            if lo[j] <= stop and j > eb:        # don't stop on entry bar (entry at open)
                out_bar, out_price, reason = j, stop, "stop-loss"
                break
            if hi[j] >= target and j > eb:
                out_bar, out_price, reason = j, target, "win-target"
                break
        if out_bar is None:
            out_bar = min(eb + max_hold, n - 1)
            out_price = cls[out_bar]
            reason = "time-exit"
        gross = (out_price - entry) / entry
        net = gross - ROUND_TRIP_COST
        trades.append(Trade(
            code=code, entry_bar=eb, entry_date=dts[eb], entry_price=float(entry),
            exit_bar=out_bar, exit_date=dts[out_bar], exit_price=float(out_price),
            reason=reason, gross_ret=float(gross), net_ret=float(net),
            hold_days=int(out_bar - eb),
        ))
        i = out_bar + 1     # only one open position per code
    return trades


# ---------------- evaluation --------------------------------------------------
@dataclass
class StrategyResult:
    name: str
    trades: list[Trade] = field(default_factory=list)

    def summary(self) -> dict:
        if not self.trades:
            return {"strategy": self.name, "trades": 0}
        rets = np.array([t.net_ret for t in self.trades])
        wins = rets[rets > 0]
        losses = rets[rets < 0]
        reasons = pd.Series([t.reason for t in self.trades]).value_counts().to_dict()
        avg_w = wins.mean() if len(wins) else 0
        avg_l = losses.mean() if len(losses) else 0
        wr = (rets > 0).mean()
        exp_ = wr * avg_w + (1 - wr) * avg_l
        return {
            "strategy": self.name,
            "trades": len(rets),
            "win%": round(float(wr * 100), 2),
            "avg%": round(float(rets.mean() * 100), 3),
            "med%": round(float(np.median(rets) * 100), 3),
            "expectancy%": round(float(exp_ * 100), 3),
            "PF": round(float(wins.sum() / -losses.sum()), 2) if losses.sum() < 0 else None,
            "avg_hold": round(float(np.mean([t.hold_days for t in self.trades])), 1),
            "stop%": round(reasons.get("stop-loss", 0) / len(rets) * 100, 1),
            "tp%":   round(reasons.get("win-target", 0) / len(rets) * 100, 1),
            "time%": round(reasons.get("time-exit", 0) / len(rets) * 100, 1),
        }


def evaluate(name: str, signal_fn: Callable[[pd.DataFrame], pd.Series],
             universe: dict[str, pd.DataFrame],
             stop_loss=0.05, take_profit=0.10, max_hold=20) -> StrategyResult:
    res = StrategyResult(name)
    for code, df in universe.items():
        d = enrich(df)
        sig = signal_fn(d)
        trades = simulate(code, d, sig, stop_loss, take_profit, max_hold)
        res.trades.extend(trades)
    return res


