def _p3_filter(d):
    bw_med = d["boll_width"].rolling(60).median()
    obv_med = d["obv_slope10"].rolling(60).median()
    return (
        (d["boll_width"] < bw_med * 1.0)
        & (d["obv_slope10"] > obv_med)
        & (d["close"] > d["open"])
    )


